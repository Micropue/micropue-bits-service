export function useConsoleI18n() {
  const locale = useState<ConsoleLocale>('console-locale', () => 'en')
  const nuxtApp = useNuxtApp()
  // PrimeVue 配置实例（模块注入）：设置内置文案语言
  const primevue = computed(() => {
    const app = nuxtApp as unknown as {
      $primevue?: { config?: { locale?: Record<string, unknown> } }
      vueApp?: { config?: { globalProperties?: { $primevue?: { config?: { locale?: Record<string, unknown> } } } } }
    }
    return app.$primevue ?? app.vueApp?.config?.globalProperties?.$primevue ?? null
  })

  function applyPrimeLocale(next: ConsoleLocale) {
    const config = primevue.value?.config
    if (!config) return
    const base = (config.locale ?? {}) as Record<string, unknown>
    config.locale = {
      ...base,
      ...(next === 'zh' ? PRIME_ZH : PRIME_EN),
      aria: {
        ...((base.aria ?? {}) as Record<string, unknown>),
        ...(next === 'zh' ? PRIME_ARIA_ZH : PRIME_ARIA_EN)
      }
    }
  }

  // t('sec.app.bound', { issuer: 'BITS' })：{name} 占位替换
  function t(key: string, vars?: Record<string, string | number>): string {
    const text = DICTS[locale.value][key] ?? EN[key] ?? key
    if (!vars) return text
    return text.replace(/\{(\w+)\}/g, (_, name: string) =>
      vars[name] === undefined ? `{${name}}` : String(vars[name]))
  }

  function setLocale(next: ConsoleLocale) {
    locale.value = next
    applyPrimeLocale(next)
    if (import.meta.client) localStorage.setItem(CONSOLE_LOCALE_KEY, next)
  }

  // SSR 首屏固定英文；客户端挂载后读回已保存语言
  function restoreLocale() {
    if (!import.meta.client) return
    const saved = localStorage.getItem(CONSOLE_LOCALE_KEY)
    if (saved === 'zh' || saved === 'en') {
      locale.value = saved
      applyPrimeLocale(saved)
    }
  }

  return { locale, t, setLocale, restoreLocale }
}

